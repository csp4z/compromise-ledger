"""Asks FIRST's EPSS API what each KEV CVE scored on the day before CISA listed it.

EPSS estimates the probability that a CVE is exploited in the next 30 days, and it takes a KEV
listing as an input. The day before the listing is therefore the model's last word without
that hint: what it predicted for a flaw that was about to be confirmed as exploited.

One request per listing date, with that date's CVEs in batches. Dates already in bronze are
skipped, so the first run resumes after a failure and later runs fetch only new listings. The
newest date is always read again, which keeps a run from being empty.
"""

from collections import defaultdict
from collections.abc import Iterator
from datetime import date, timedelta
from importlib.metadata import version

from ledger_crawl import CrawlContext, CrawlerMeta, FetchedDocument, KevCve, RateLimit
from ledger_crawl.errors import HttpStatusError

API_URL = "https://api.first.org/data/v1/epss"
# The API returns at most 100 scores per page, and a long CVE list makes a long URL.
BATCH = 80
# FIRST asks for attribution and names no license (https://www.first.org/epss/faq). The scores
# are generated by Empirical Security and published by FIRST.
EPSS_NOTICE = (
    "EPSS scores from the Exploit Prediction Scoring System (https://www.first.org/epss), "
    "generated by Empirical Security and published by FIRST."
)
# The API's answer for a date it has no scores for at all.
NO_SCORES_FOR_DATE = 422


def score_date(kev: KevCve) -> date:
    return kev.date_added - timedelta(days=1)


def score_params(cve_ids: list[str], day: date) -> dict[str, str | int]:
    return {"cve": ",".join(cve_ids), "date": day.isoformat()}


def batches(kev_cves: tuple[KevCve, ...]) -> Iterator[tuple[date, list[str]]]:
    """(score date, CVE IDs) for every request, oldest date first."""
    by_day: dict[date, list[str]] = defaultdict(list)
    for kev in kev_cves:
        by_day[score_date(kev)].append(kev.cve_id)
    for day in sorted(by_day):
        cve_ids = sorted(by_day[day])
        for start in range(0, len(cve_ids), BATCH):
            yield day, cve_ids[start : start + BATCH]


class EpssCrawler:
    meta = CrawlerMeta(
        id="epss",
        version=version("ledger-crawler-epss"),
        description=(
            "FIRST Exploit Prediction Scoring System: each KEV CVE's score on the day "
            "before CISA listed it."
        ),
        schedule="50 22 * * *",
        rate_limit=RateLimit(requests=1, per_seconds=1),
        license="LicenseRef-FIRST-EPSS-Usage",
        attribution=EPSS_NOTICE,
        allowed_hosts=("api.first.org",),
        content_types=("application/json",),
        max_bytes=1024 * 1024,
        retries=3,
        inputs=("kev_cves",),
        after=("cisa-kev",),
    )

    def fetch(self, ctx: CrawlContext) -> Iterator[FetchedDocument]:
        if not ctx.kev_cves:
            raise ValueError("no KEV CVEs in silver yet; crawl and parse cisa-kev first")
        newest = max(score_date(kev) for kev in ctx.kev_cves)
        for day, cve_ids in batches(ctx.kev_cves):
            params = score_params(cve_ids, day)
            if day != newest and ctx.seen(API_URL, params=params):
                continue
            try:
                yield ctx.get(API_URL, params=params)
            except HttpStatusError as exc:
                # One date without scores must not stop the others; it is asked for again on
                # the next run.
                if exc.status != NO_SCORES_FOR_DATE:
                    raise
